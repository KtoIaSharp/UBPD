static const char *companyNameLookup(uint16_t id) {
  int lo = 0, hi = COMPANY_COUNT - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2;
    if (COMPANY_TABLE[mid].id == id) return COMPANY_TABLE[mid].name;
    if (COMPANY_TABLE[mid].id < id) lo = mid + 1;
    else hi = mid - 1;
  }
  return "";
}
